var ES = {};
document.querySelectorAll('[data-i18n]').forEach(function (el) { ES[el.dataset.i18n] = el.textContent; });
document.querySelectorAll('[data-i18n-ph]').forEach(function (el) { ES[el.dataset.i18nPh] = el.placeholder; });

var lang = 'es';

function waLink(msg) {
  return 'https://wa.me/' + WHATSAPP + (msg ? '?text=' + encodeURIComponent(msg) : '');
}

function openWa(url) {
  var w = window.open(url, '_blank', 'noopener');
  if (!w) { try { (window.top || window).location.href = url; } catch (e) { window.location.href = url; } }
}

function applyLang(next) {
  lang = next;
  var dict = next === 'pt' ? PT : ES;
  document.documentElement.lang = next === 'pt' ? 'pt' : 'es';
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    var v = dict[el.dataset.i18n]; if (v) el.textContent = v;
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
    var v = dict[el.dataset.i18nPh]; if (v) el.placeholder = v;
  });
  document.querySelectorAll('.langs button').forEach(function (b) {
    b.setAttribute('aria-pressed', String(b.dataset.lang === next));
  });
  var intro = next === 'pt'
    ? 'Olá Aserradero Punky, quero consultar sobre machimbre, caibros ou ripas.'
    : 'Hola Aserradero Punky, quiero consultar por machimbre, tirantes o clavadores.';
  document.querySelectorAll('[data-wa]').forEach(function (a) {
    a.href = waLink(intro); a.target = '_blank'; a.rel = 'noopener';
  });
  try { localStorage.setItem('punky-lang', next); } catch (e) {}
}

document.querySelectorAll('.langs button').forEach(function (b) {
  b.addEventListener('click', function () { applyLang(b.dataset.lang); });
});

document.getElementById('cotizar').addEventListener('submit', function (e) {
  e.preventDefault();
  var f = e.target;
  function g(n) { return (f.elements[n] && f.elements[n].value || '').trim(); }
  var es = lang === 'es';
  var lines = [
    es ? 'Hola Aserradero Punky, quiero cotizar:' : 'Olá Aserradero Punky, quero um orçamento:',
    (es ? 'Nombre/Empresa: ' : 'Nome/Empresa: ') + g('nombre'),
    (es ? 'Contacto: ' : 'Contato: ') + g('contacto'),
    (es ? 'Localidad: ' : 'Cidade: ') + (g('localidad') || '-'),
    (es ? 'Producto: ' : 'Produto: ') + g('producto'),
    (es ? 'Medida y volumen: ' : 'Medida e volume: ') + (g('volumen') || '-'),
    (es ? 'Detalle: ' : 'Detalhes: ') + (g('detalle') || '-')
  ];
  openWa(waLink(lines.join('\n')));
});

